export function getTranslation(lang, path) {
  const parts = path.split(".");
  let node = translations[lang] || translations.en;
  for (const p of parts) {
    node = node?.[p];
    if (node === undefined) break;
  }
  if (node === undefined) {
    // Fall back to English rather than showing a raw key if a translation is
    // missing for the selected language — a missing hi/kn string should never
    // look like a rendering bug, it should just silently show the English label.
    node = translations.en;
    for (const p of parts) node = node?.[p];
  }
  return node ?? path;
}
